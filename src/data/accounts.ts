export type AccountStatus = "critical" | "watch" | "healthy";

export type Account = {
  id: string;
  name: string;
  arrLakhs: number;
  arr: string;
  risk: number;
  status: AccountStatus;
  reason: string;
  lastActive: string;
  lastActiveSort: number;
  renewal: string;
  renewalSort: number;
  owner: "Meera" | "Arjun" | "Ritika";
  seatsUsed: number;
  seatsTotal: number;
};

export const accountsTotalCount = 186;

export function statusFromRisk(risk: number): AccountStatus {
  if (risk >= 75) return "critical";
  if (risk >= 50) return "watch";
  return "healthy";
}

function account(
  partial: Omit<Account, "status"> & { risk: number },
): Account {
  return {
    ...partial,
    status: statusFromRisk(partial.risk),
  };
}

